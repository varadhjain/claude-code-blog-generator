/**
 * GitHub Gist Uploader
 *
 * Upload annotation results to a public GitHub Gist using gh CLI
 */

import { execSync } from 'child_process';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import type { AnnotatorResult } from './user-annotations';

export interface GistUploadOptions {
  isPublic?: boolean; // Default: true (public gist)
  description?: string;
}

export interface GistUploadResult {
  url: string;
}

/**
 * Upload annotation results to GitHub Gist using gh CLI
 */
export async function uploadToGist(
  result: AnnotatorResult,
  sessionName: string,
  options: GistUploadOptions = {}
): Promise<GistUploadResult> {
  // Check if gh CLI is installed
  try {
    execSync('gh --version', { stdio: 'ignore' });
  } catch (error) {
    throw new Error(
      'gh CLI not found. Install it from https://cli.github.com/ and run `gh auth login`'
    );
  }

  // Create filename from session name
  const filename = sessionName.endsWith('.jsonl')
    ? sessionName.replace('.jsonl', '-annotations.md')
    : `${sessionName}-annotations.md`;

  // Prepare gist content as human-readable Markdown
  const gistContent = formatAsMarkdown(result, sessionName);

  // Write to temporary file
  const tempFile = path.join(os.tmpdir(), filename);
  fs.writeFileSync(tempFile, gistContent, 'utf-8');

  try {
    // Create gist using gh CLI
    const visibility = options.isPublic !== false ? '--public' : '--secret';
    const description =
      options.description || `User Message Annotations for ${sessionName}`;

    const command = `gh gist create ${visibility} -d "${description}" "${tempFile}"`;
    const output = execSync(command, { encoding: 'utf-8' }).trim();

    // Clean up temp file
    fs.unlinkSync(tempFile);

    // gh gist create returns the URL
    return {
      url: output,
    };
  } catch (error) {
    // Clean up temp file on error
    if (fs.existsSync(tempFile)) {
      fs.unlinkSync(tempFile);
    }
    throw new Error(`Failed to create gist: ${error}`);
  }
}

/**
 * Format annotation results as human-readable Markdown
 */
function formatAsMarkdown(result: AnnotatorResult, sessionName: string): string {
  const lines: string[] = [];

  // Header
  lines.push(`# User Message Annotations: ${sessionName}`);
  lines.push('');
  lines.push(`**Generated:** ${new Date().toISOString()}`);
  lines.push('');
  lines.push('---');
  lines.push('');

  // Summary Stats
  lines.push('## 📊 Summary');
  lines.push('');
  lines.push(`- **Total messages in session:** ${result.stats.totalMessages}`);
  lines.push(`- **User messages analyzed:** ${result.stats.userMessages}`);
  lines.push(`- 🟢 **Green (new tasks):** ${result.stats.greenCount}`);
  lines.push(`- 🟡 **Yellow (steering):** ${result.stats.yellowCount}`);
  lines.push(`- 🔴 **Red (restarts):** ${result.stats.redCount}`);
  lines.push(`- **AI API calls:** ${result.stats.totalApiCalls} (1 phase detection + ${result.stats.userMessages} annotations)`);
  lines.push('');

  // Detected Phases
  lines.push('## 📋 Detected Phases');
  lines.push('');
  if (result.phases.phases.length === 0) {
    lines.push('_No phases detected_');
  } else {
    result.phases.phases.forEach((phase) => {
      lines.push(`### ${phase.phaseId}. ${phase.phaseName}`);
      lines.push('');
      lines.push(`**Messages:** ${phase.messageIndices.join(', ')}`);
      lines.push('');
      lines.push(`**Description:** ${phase.description}`);
      lines.push('');
    });
  }

  // Annotated Messages
  lines.push('## 💬 Annotated Messages');
  lines.push('');

  result.annotations.forEach((ann) => {
    const colorEmoji = ann.color === 'green' ? '🟢' : ann.color === 'yellow' ? '🟡' : '🔴';

    lines.push(`### ${colorEmoji} Message #${ann.messageIndex}`);
    lines.push('');
    lines.push('**User said:**');
    lines.push('> ' + ann.content.split('\n').join('\n> '));
    lines.push('');
    lines.push(`**Annotation:** ${ann.annotation}`);
    lines.push('');
    lines.push(`**Reasoning:** ${ann.reasoning}`);
    lines.push('');
    lines.push('---');
    lines.push('');
  });

  // Footer
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('_Generated by [Claude Code Blog Generator](https://github.com/varadhjain/claude-code-blog-generator)_');
  lines.push('');

  return lines.join('\n');
}
