import assert from 'node:assert/strict';
import {mkdtempSync, writeFileSync, appendFileSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openDb} from '../src/search/db';
import {indexFile} from '../src/search/indexer';
import {buildDigest} from '../src/reflect/digest';
const root=mkdtempSync(join(tmpdir(),'ccblog-reader-'));
const timestamp='2026-10-05T12:00:00Z';
const record=(type:string,payload:any)=>JSON.stringify({timestamp,type,payload})+'\n';
const meta=(cwd:string)=>record('session_meta',{cwd});
const msg=(role:string,text:string,channel?:string)=>record('response_item',{type:'message',role,channel,content:[{type:role==='user'?'input_text':'output_text',text}]});
const path=join(root,'session.jsonl');
const dbPath=join(root,'index.db');
let db=openDb(dbPath);
try {
 writeFileSync(path,meta('/projects/firm')+msg('user','Help me fix the scheduled backup reader, please.')+record('event_msg',{type:'user_message',message:'Help me fix the scheduled backup reader, please.'})+msg('assistant','I will preserve originals and verify the derived records.','commentary')+msg('assistant','INTERNAL_SECRET','analysis')+msg('developer','SYSTEM_SECRET')+record('response_item',{type:'function_call_output',output:'TOOL_SECRET'})+msg('assistant','The repaired reader preserves timestamps and original captures.','final'));
 assert.equal(indexFile(db,path,'codex').messagesIndexed,3);
 const rows=db.prepare('SELECT user_text,assistant_text FROM messages_fts').all();
 assert.equal(rows.length,3);
 assert(!JSON.stringify(rows).includes('SECRET'));
 const digest=buildDigest(db,{sinceMs:Date.parse('2026-10-01'),untilMs:Date.parse('2026-10-06')});
 assert.equal(digest.total_sessions,1);assert.equal(digest.total_messages,3);
 assert.equal((db.prepare('SELECT cwd,last_msg_at FROM sessions').get() as any).cwd,'/projects/firm');
 assert.equal(indexFile(db,path,'codex').messagesIndexed,0);
 appendFileSync(path,msg('user','Now check that appending preserves earlier records.'));
 assert.equal(indexFile(db,path,'codex').messagesIndexed,1);
 assert.equal((db.prepare('SELECT count(*) AS n FROM messages_fts').get() as any).n,4);
 const mind=join(root,'mind-session.jsonl');
 writeFileSync(mind,meta('/projects/personal-software/mind')+msg('user','PRIVATE_JOURNAL'));
 assert.equal(indexFile(db,mind,'codex').messagesIndexed,0);
 assert(!JSON.stringify(db.prepare('SELECT * FROM messages_fts').all()).includes('PRIVATE_JOURNAL'));
 const transition=join(root,'transition.jsonl');
 writeFileSync(transition,meta('/projects/firm')+msg('user','Existing nonprivate work should be removed on private transition.'));
 assert.equal(indexFile(db,transition,'codex').messagesIndexed,1);
 appendFileSync(transition,record('event_msg',{type:'irrelevant',text:'x'.repeat(2*1024*1024)})+record('turn_context',{cwd:'/projects/personal-software/mind'})+msg('user','LATE_PRIVATE_SENTINEL'));
 assert.equal(indexFile(db,transition,'codex').messagesIndexed,0);
 assert.equal((db.prepare("SELECT count(*) AS n FROM sessions WHERE session_id='transition'").get() as any).n,0);
 assert(!JSON.stringify(db.prepare('SELECT * FROM messages_fts').all()).includes('LATE_PRIVATE_SENTINEL'));
 const legacyPrivate=join(root,'legacy-private.jsonl');
 writeFileSync(legacyPrivate,meta('/projects/firm')+JSON.stringify({timestamp,type:'user_input',turn_context:{cwd:'/private/.mind'},text:'LEGACY_PRIVATE'})+'\n');
 assert.equal(indexFile(db,legacyPrivate,'codex').messagesIndexed,0);
 assert(!JSON.stringify(db.prepare('SELECT * FROM messages_fts').all()).includes('LEGACY_PRIVATE'));
 const unknown=join(root,'unknown.jsonl');writeFileSync(unknown,msg('user','UNKNOWN_SCOPE'));
 assert.equal(indexFile(db,unknown,'codex').messagesIndexed,0);
 const claude=join(root,'claude.jsonl');
 writeFileSync(claude,JSON.stringify({timestamp,cwd:'/projects/firm',type:'user',message:{role:'user',content:'Keep my existing Claude record.'}})+'\n');
 assert.equal(indexFile(db,claude,'claude-code').messagesIndexed,1);
 db.prepare("DELETE FROM schema_meta WHERE key='codex_reader'").run();db.close();db=openDb(dbPath);
 assert.equal((db.prepare("SELECT count(*) AS n FROM sessions WHERE source='claude-code'").get() as any).n,1);
 assert.equal((db.prepare("SELECT count(*) AS n FROM sessions WHERE source='codex'").get() as any).n,0);
 assert.equal(indexFile(db,path,'codex').messagesIndexed,4);
 db.close();db=openDb(dbPath);
 assert.equal(indexFile(db,path,'codex').messagesIndexed,0);
 console.log('PASS: current session/digest, privacy, incremental retry and migration');
} finally {db.close();rmSync(root,{recursive:true,force:true});}
